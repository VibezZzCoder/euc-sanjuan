import {header} from './headers.mjs';
// Writes data/streets-cache.bin (the streets layout startup cache; js/sj-streets-cache.js) from the runtime path, on the
// current code and data. Usage (from the fork root): node tools/build-streets-cache.mjs [--check]
//   --check  rebuild in memory and compare with the file on disk (exit 1 when missing or different).
// Run it after any change to the city data or to any area that merges before `streets` (package time). A stale file is
// never wrong in the game — its digest no longer matches and the runtime path runs — only slower.
import {readFileSync,writeFileSync,existsSync,readdirSync} from 'node:fs';
import {registerHooks} from 'node:module';
import zlib from 'node:zlib';
process.env.SJ_STREETS_CACHE='0';   // build from the runtime path, never from an existing cache
const root=new URL('../',import.meta.url),check=process.argv.includes('--check');
registerHooks({resolve(s,c,next){return s==='three/webgpu'?{url:new URL('vendor/three/build/three.webgpu.js',root).href,shortCircuit:true}:next(s,c);}});
globalThis.fetch=async url=>{const b=readFileSync(url);return {ok:true,json:async()=>JSON.parse(b),arrayBuffer:async()=>b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength)};};
const C=await import(new URL('js/sj-streets-cache.js',root));
// 1. The content key (js/sj-streets-cache-key.js) — written first, so the layout module imports the current key.
const unlisted=readdirSync(new URL('data/',root)).filter(f=>!C.CACHE_DATA.includes(f)&&!C.CACHE_IGNORED.includes(f));
if(unlisted.length){console.log('data/ has files not in CACHE_DATA / CACHE_IGNORED (js/sj-streets-cache.js):',unlisted.join(', '));process.exit(1);}
const {key:source,modules}=await C.contentKey(new URL('js/',root)),keyFile=new URL('js/sj-streets-cache-key.js',root);
const keyText=`${header('js/sj-streets-cache-key.js')}\n// Generated by tools/build-streets-cache.mjs: content key of the world-build modules and data files (js/sj-streets-cache.js).\nexport const STREETS_CONTENT_KEY=[${source[0]},${source[1]}];\n`;
const keyStale=!existsSync(keyFile)||readFileSync(keyFile,'utf8')!==keyText;
if(keyStale&&!check)writeFileSync(keyFile,keyText);
if(keyStale&&check){console.log('sj-streets-cache-key.js is STALE');process.exit(1);}
const W=await import(new URL('js/sj-world.js',root));
const L=await import(new URL('js/sj-streets-layout.js',root));
let args=null,layout=null;const orig=W.AREA_LAYOUTS.streets;
W.AREA_LAYOUTS.streets=a=>{args={...a,surface:a.surface.slice()};layout=orig(a);return layout;};
await W.loadCity();
const {nx,nz}=args.terrain,land=args.land;
// Cells whose drawing is blocked by private ground (water excluded): the complete list, so the cached draw test is exact.
const privateCells=[];for(let j=0;j<nz-1;j++)for(let i=0;i<nx-1;i++){const k=j*nx+i;
  if(land[k]&&land[k+1]&&land[k+nx]&&land[k+nx+1]&&layout.drawBlocked(i,j,'free'))privateCells.push(k);}
const digest=L.streetsCode();
const payload=C.encodeLayout(layout,{remapped:layout.remappedCells,covered:layout.covered,privateCells});
const deflated=zlib.deflateRawSync(payload,{level:9});
const head=Buffer.alloc(20);head.write('SJS1',0,'latin1');head.writeUInt32LE(C.CACHE_VERSION,4);head.writeUInt32LE(digest[0],8);head.writeUInt32LE(digest[1],12);
head.writeUInt32LE(payload.length,16);
const file=Buffer.concat([head,deflated]),out=new URL('data/streets-cache.bin',root);
console.log(JSON.stringify({modules:modules.length,contentKey:source,pieces:layout.paved.length,privateCells:privateCells.length,payload:payload.length,file:file.length,digest}));
if(file.length>1e6)console.warn('streets-cache.bin is above 1 MB');
if(check){const same=existsSync(out)&&Buffer.compare(readFileSync(out),file)===0;console.log(same?`streets-cache.bin is current (header key ${digest.join(',')}; a browser using it reports the same key)`:'streets-cache.bin is MISSING or STALE');process.exit(same?0:1);}
writeFileSync(out,file);console.log('wrote',out.pathname);
