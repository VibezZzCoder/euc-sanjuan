"""Bake mapped natural ground polygons (OSM natural=beach|sand|bare_rock|rock|scrub|wood|wetland, landuse=meadow, plus
landuse=military|industrial as 'paved' operational ground that stays town-coloured) into
js/sj-ground-osm.js for the `ground` area's terrain classes. Offline: reads the cached OSM extract only.

Run: python3 tools/build-ground-osm.py   (needs pyproj)
OSM data © OpenStreetMap contributors, ODbL.
"""
import os
from pathlib import Path
import json
from pyproj import Transformer, CRS

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(os.environ.get('SJ_DATA_DIR', ROOT / 'inputs')) / 'osm-old-san-juan.json'
OUT = ROOT / 'js/sj-ground-osm.js'
F = Transformer.from_crs(4326, CRS.from_proj4('+proj=aeqd +lat_0=18.4655 +lon_0=-66.1167 +datum=WGS84 +units=m'), always_xy=True)
CLASS = {'beach': 'sand', 'sand': 'sand', 'bare_rock': 'rock', 'rock': 'rock', 'scrub': 'scrub', 'wood': 'wood',
         'wetland': 'scrub', 'meadow': 'meadow'}

rows = []
for e in json.loads(SRC.read_text())['elements']:
    t = e.get('tags', {})
    if e['type'] != 'way' or 'highway' in t or 'building' in t: continue
    kind = CLASS.get(t.get('natural')) or (CLASS['meadow'] if t.get('landuse') == 'meadow' else None) \
        or ('paved' if t.get('landuse') in ('military', 'industrial') else None)
    g = e.get('geometry') or []
    if not kind or len(g) < 4 or g[0] != g[-1]: continue
    ring = []
    for p in g[:-1]:
        x, n = F.transform(p['lon'], p['lat'])
        ring.append([round(x, 1), round(-n, 1)])
    rows.append((e['id'], kind, ring))
rows.sort()
# Sports surfaces: leisure=pitch|track|playground polygons. Scatter never stands on them
# (sj-ground-classes.js scatterCandidates); their classes/colours are untouched.
sports = []
for e in json.loads(SRC.read_text())['elements']:
    t = e.get('tags', {})
    kind = t.get('leisure')
    g = e.get('geometry') or []
    if e['type'] != 'way' or kind not in ('pitch', 'track', 'playground') or len(g) < 4 or g[0] != g[-1]: continue
    ring = []
    for p in g[:-1]:
        x, n = F.transform(p['lon'], p['lat'])
        ring.append([round(x, 1), round(-n, 1)])
    sports.append((e['id'], kind, t.get('sport', ''), t.get('surface', ''), ring))
sports.sort()
lines = ['/*! El Viejo San Juan: EUC Thrills — (c) 2026 VibezZzCoder — MIT code — https://github.com/VibezZzCoder/euc-sanjuan — Data: © OpenStreetMap contributors, ODbL 1.0 */\n' '// Generated by tools/build-ground-osm.py from the cached OSM extract — do not edit. © OpenStreetMap contributors, ODbL.',
         '// Mapped natural ground: [osmWayId, class, ring [[x,z]…] in the city projection (x east, z south, metres)].',
         'export const GROUND_OSM=[']
for i, k, r in rows:
    lines.append(f'[{i},{json.dumps(k)},{json.dumps(r, separators=(",", ":"))}],')
lines.append('];')
lines.append('// Mapped sports surfaces: [osmWayId, leisure (pitch|track|playground), sport, surface, ring [[x,z]…]].')
lines.append('export const GROUND_SPORTS=[')
for i, k, sp, su, r in sports:
    lines.append(f'[{i},{json.dumps(k)},{json.dumps(sp)},{json.dumps(su)},{json.dumps(r, separators=(",", ":"))}],')
lines.append('];')
OUT.write_text('\n'.join(lines) + '\n')
print(len(rows), 'polygons,', len(sports), 'sports', OUT.stat().st_size, 'bytes')
